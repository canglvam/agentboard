// Deploy AgentBoard.
// - bscTestnet: deploys MockAgentId first, then AgentBoard(mock).
// - bsc (mainnet): deploys AgentBoard against the REAL Agent ID registry
//   0x60b9262456de011f7d15a54cdd8c48baaa8b022f. Only run after funding.
// Writes deployments/<network>.json and frontend/config.js.
// Private key comes from env PRIVATE_KEY (never committed, never printed).
const hre = require("hardhat");
const fs = require("fs");
const path = require("path");

const MAINNET_REGISTRY = "0x60b9262456de011f7d15a54cdd8c48baaa8b022f";
const RPC_URLS = {
  bscTestnet: "https://bsc-testnet.publicnode.com",
  bsc: "https://bsc.publicnode.com",
};
const EXPLORERS = {
  bscTestnet: "https://testnet.bscscan.com",
  bsc: "https://bscscan.com",
};

async function main() {
  const network = hre.network.name;
  if (network !== "bscTestnet" && network !== "bsc") {
    throw new Error("Deploy only to bscTestnet or bsc (got " + network + ")");
  }
  const [deployer] = await hre.ethers.getSigners();
  const chainId = Number((await hre.ethers.provider.getNetwork()).chainId);
  const balance = await hre.ethers.provider.getBalance(deployer.address);
  console.log("Network:", network, "chainId:", chainId);
  console.log("Deployer:", deployer.address);
  console.log("Deployer balance:", hre.ethers.formatEther(balance), "BNB");
  if (balance < hre.ethers.parseEther("0.005")) {
    throw new Error("Deployer balance too low (< 0.005 BNB). Fund " + deployer.address + " first.");
  }

  let registryAddress;
  let mockAddress = null;
  if (network === "bsc") {
    registryAddress = MAINNET_REGISTRY;
    console.log("Using REAL Agent ID registry:", registryAddress);
  } else {
    const Mock = await hre.ethers.getContractFactory("MockAgentId");
    const mock = await Mock.deploy();
    await mock.waitForDeployment();
    mockAddress = await mock.getAddress();
    registryAddress = mockAddress;
    console.log("MockAgentId deployed:", mockAddress);
  }

  const Board = await hre.ethers.getContractFactory("AgentBoard");
  const board = await Board.deploy(registryAddress);
  await board.waitForDeployment();
  const boardAddress = await board.getAddress();
  const receipt = await board.deploymentTransaction().wait();
  console.log("AgentBoard deployed:", boardAddress);
  console.log("Explorer:", EXPLORERS[network] + "/address/" + boardAddress);

  const deployment = {
    network,
    chainId,
    deployer: deployer.address,
    agentBoard: boardAddress,
    agentIdRegistry: registryAddress,
    mockAgentId: mockAddress,
    deployBlock: receipt.blockNumber,
    deployTx: receipt.hash,
    deployedAt: new Date().toISOString(),
    explorer: EXPLORERS[network] + "/address/" + boardAddress,
  };
  const outDir = path.join(__dirname, "..", "deployments");
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, network + ".json"), JSON.stringify(deployment, null, 2));

  const config = {
    network,
    chainId,
    rpcUrl: RPC_URLS[network],
    explorer: EXPLORERS[network],
    agentBoard: boardAddress,
    agentIdRegistry: registryAddress,
    deployBlock: receipt.blockNumber,
  };
  const configJs =
    "// Auto-generated by scripts/deploy.js — do not edit by hand.\n" +
    "window.AGENTBOARD_CONFIG = " + JSON.stringify(config, null, 2) + ";\n";
  fs.writeFileSync(path.join(__dirname, "..", "frontend", "config.js"), configJs);
  console.log("Wrote deployments/" + network + ".json and frontend/config.js");
}

main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
